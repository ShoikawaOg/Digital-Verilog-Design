module alu (
    input  [31:0] A,
    input  [31:0] B,
    input  [3:0]  opcode,

    output reg [31:0] result,
    output reg        zero,
    output reg        negative,
    output reg        carry,
    output reg        overflow
);

    reg [32:0] temp;

    always @(*) begin

        // Default values
        result   = 32'b0;
        zero     = 1'b0;
        negative = 1'b0;
        carry    = 1'b0;
        overflow = 1'b0;
        temp     = 33'b0;

        case (opcode)

            // =================================================
            // ADD
            // =================================================

            4'b0000: begin

                temp = {1'b0, A} + {1'b0, B};

                result = temp[31:0];
                carry  = temp[32];

                // Signed overflow
                overflow = (~(A[31] ^ B[31])) &
                           (result[31] ^ A[31]);

            end


            // =================================================
            // SUB
            // =================================================

            4'b0001: begin

                result = A - B;

                // Carry = 1 means NO borrow
                carry = (A >= B);

                // Signed overflow
                overflow = (A[31] ^ B[31]) &
                           (result[31] ^ A[31]);

            end


            // =================================================
            // AND
            // =================================================

            4'b0010: begin

                result = A & B;

            end


            // =================================================
            // OR
            // =================================================

            4'b0011: begin

                result = A | B;

            end


            // =================================================
            // XOR
            // =================================================

            4'b0100: begin

                result = A ^ B;

            end


            // =================================================
            // NOT
            // =================================================

            4'b0101: begin

                result = ~A;

            end


            // =================================================
            // LOGICAL LEFT SHIFT
            // =================================================

            4'b0110: begin

                result = A << B[4:0];

            end


            // =================================================
            // LOGICAL RIGHT SHIFT
            // =================================================

            4'b0111: begin

                result = A >> B[4:0];

            end


            // =================================================
            // ARITHMETIC RIGHT SHIFT
            // =================================================

            4'b1000: begin

                result = $signed(A) >>> B[4:0];

            end


            // =================================================
            // SIGNED LESS THAN
            // =================================================

            4'b1001: begin

                result = ($signed(A) < $signed(B))
                         ? 32'd1
                         : 32'd0;

            end


            // =================================================
            // UNSIGNED LESS THAN
            // =================================================

            4'b1010: begin

                result = (A < B)
                         ? 32'd1
                         : 32'd0;

            end


            // =================================================
            // INVALID OPCODE
            // =================================================

            default: begin

                result   = 32'b0;
                carry    = 1'b0;
                overflow = 1'b0;

            end

        endcase


        // =====================================================
        // COMMON FLAGS
        // =====================================================

        zero     = (result == 32'b0);
        negative = result[31];

    end

endmodule
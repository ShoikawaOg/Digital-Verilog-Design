`timescale 1ns / 1ps

module pwm_generator_tb;

    reg clk;
    reg reset;
    reg enable;

    reg [7:0] duty_cycle;

    wire pwm_out;


    // =====================================================
    // DUT
    // =====================================================

    pwm_generator #(
        .COUNTER_WIDTH(8)
    ) uut (
        .clk(clk),
        .reset(reset),
        .enable(enable),
        .duty_cycle(duty_cycle),
        .pwm_out(pwm_out)
    );


    // =====================================================
    // CLOCK
    // 10 ns period = 100 MHz
    // =====================================================

    always #5 clk = ~clk;


    // =====================================================
    // TEST
    // =====================================================

    initial begin

        clk        = 1'b0;
        reset      = 1'b1;
        enable     = 1'b0;
        duty_cycle = 8'd0;


        // =================================================
        // RESET
        // =================================================

        #20;

        reset  = 1'b0;
        enable = 1'b1;


        // =================================================
        // 0% DUTY
        // =================================================

        duty_cycle = 8'd0;

        $display("Testing 0%% duty cycle");

        #2560;


        // =================================================
        // 25% DUTY
        // =================================================

        duty_cycle = 8'd64;

        $display("Testing 25%% duty cycle");

        #2560;


        // =================================================
        // 50% DUTY
        // =================================================

        duty_cycle = 8'd128;

        $display("Testing 50%% duty cycle");

        #2560;


        // =================================================
        // 75% DUTY
        // =================================================

        duty_cycle = 8'd192;

        $display("Testing 75%% duty cycle");

        #2560;


        // =================================================
        // 100% DUTY
        // =================================================

        duty_cycle = 8'd255;

        $display("Testing 100%% duty cycle");

        #2560;


        // =================================================
        // DISABLE
        // =================================================

        enable = 1'b0;

        #20;

        if (pwm_out == 1'b0)
            $display("PASS: PWM disabled");
        else
            $display("FAIL: PWM disabled");


        // =================================================
        // COMPLETE
        // =================================================

        $display("");
        $display("========================================");
        $display("PWM BASIC TEST COMPLETE");
        $display("========================================");

        $finish;

    end

endmodule